void locale_set_french(bool value) { french = value; }
bool locale_is_french(void) { return french; }
const char *tr(const char *text) {
    if (french || !text) return text;
    for (unsigned i = 0; i < sizeof(words)/sizeof(words[0]); ++i)
        if (strcmp(words[i].fr, text) == 0) return words[i].en;
    return text;
}
